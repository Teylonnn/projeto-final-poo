    public TelaDeEstatistica(List<Aluno> alunos, CadastroAluno cadastroAluno) {
        initComponents();
        //this.alunos = alunos;
        // retorna a lista de alunos no db
        alunos = AlunoDB.ListarAlunos();
        //setAlunos(AlunoDB.ListarAlunos());
        this.cadastroAluno = cadastroAluno;
        
        valorDado.setText(String.valueOf(alunos.size())); 
        
        // Captação dos alunos mais novo e mais velho;
        int idAlunoMaisNovo = cadastroAluno.alunoMaisNovo(alunos);
        alunoMaisNovo = cadastroAluno.obterAluno(alunos, idAlunoMaisNovo);
        int idAlunoMaisVelho = cadastroAluno.alunoMaisVelho(alunos);
        alunoMaisVelho = cadastroAluno.obterAluno(alunos, idAlunoMaisVelho);
        
        if(alunoMaisNovo!=null || alunoMaisVelho!=null){
            // Criação das tabelas na interface com os dados;
            javax.swing.table.DefaultTableModel alunoMaisNovoT = (javax.swing.table.DefaultTableModel) alunoMaisNovoResult.getModel();
            alunoMaisNovoT.setRowCount(0);
            alunoMaisNovoT.addRow(new Object[]{
                alunoMaisNovo.getMatricula(),
                alunoMaisNovo.getCPF(),
                alunoMaisNovo.getNome(),
                alunoMaisNovo.getIdade(),
                alunoMaisNovo.getDataNascimento().format(this.formatoDaData),
                alunoMaisNovo.getTelefone()   
            });
        
        
            javax.swing.table.DefaultTableModel alunoMaisVelhoT = (javax.swing.table.DefaultTableModel) alunoMaisVelhoResult.getModel();
            alunoMaisVelhoT.setRowCount(0);
            alunoMaisVelhoT.addRow(new Object[]{
                alunoMaisVelho.getMatricula(),
                alunoMaisVelho.getCPF(),
                alunoMaisVelho.getNome(),
                alunoMaisVelho.getIdade(),
                alunoMaisVelho.getDataNascimento().format(this.formatoDaData),
                alunoMaisVelho.getTelefone()   
            });
            
            
        } 
        
    }
 
