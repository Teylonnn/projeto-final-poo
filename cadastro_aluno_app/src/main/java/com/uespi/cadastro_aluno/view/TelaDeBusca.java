    private void botaoBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botaoBuscarActionPerformed
        // TODO add your handling code here:
        String matDoAluno = CampoMat.getText().trim(); // Captação dos dados digitados pelo aluno;
        
        if(matDoAluno.isEmpty()){ // Verificação se os campos foram preenchidos;
            javax.swing.JOptionPane.showMessageDialog(this, "Erro !!! Preencha os campos.", "Aviso", 
                    javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Criação de objeto aluno para obter o retorno da busca e capturar o vetor que está na classe Aluno;
        Aluno aluno;
        aluno = cadastroAluno.obterAluno(this.getAlunos(), Integer.parseInt(matDoAluno));
        //aluno = AlunoDB.BuscarPorMatricula(Integer.parseInt(matDoAluno));

        // Verificação se o retorno de obterAluno foi nulo, logo, nada encontrado.
        if(aluno == null){
            javax.swing.JOptionPane.showMessageDialog(this, "Aluno não encontrado.", "Aviso", 
                    javax.swing.JOptionPane.WARNING_MESSAGE);
            CampoMat.setText(" ");
            return;
        }
        
        // Configuração da tabela de resultado da busca;
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) resultados.getModel();
        
        modelo.setRowCount(0);
        
        modelo.addRow(new Object[]{
            aluno.getMatricula(), 
            aluno.getCPF(), 
            aluno.getNome(), 
            aluno.getIdade(), 
            aluno.getDataNascimento().format(this.formatoDaData), 
            aluno.getTelefone()
        });
        
        CampoMat.setText(" ");
    }//GEN-LAST:event_botaoBuscarActionPerformed


