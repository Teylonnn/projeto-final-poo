    public TelaDeListagem(List<Aluno> alunos) {
        initComponents();
        //this.alunos = alunos;
        // retorna a lista de alunos no db
        alunos = AlunoDB.ListarAlunos();

        this.TotalAlunos.setText(String.valueOf(alunos.size()));
        
        // Criação do rotúlo e configuração;
        statusDeAlunosCad = new JLabel();
        statusDeAlunosCad.setForeground(Color.WHITE);
        statusDeAlunosCad.setFont(new Font("Arial", Font.PLAIN, 14));
        
        // Verificação sobre a existência de dados em alunos e exibição dos dados;
        if(alunos.isEmpty()){
            statusDeAlunosCad.setText("Sem alunos cadastrados ainda.");
            PainelRodape.add(statusDeAlunosCad);
        }
        
        // Adição dos dados na tabela;
         javax.swing.table.DefaultTableModel alunosCad = (javax.swing.table.DefaultTableModel) alunosCadastrados.getModel();
         alunosCad.setRowCount(0);
         
         for(Aluno aluno: alunos){
             alunosCad.addRow(new Object[]{
                aluno.getMatricula(),
                aluno.getCPF(),
                aluno.getNome(),
                aluno.getIdade(),
                aluno.getDataNascimento().format(this.formatoDaData),
                aluno.getTelefone()   
            });
         }
    }
    
    
